"""Authored source/units contract; pure helpers, with no workbook or file I/O."""
from __future__ import annotations
from copy import deepcopy
import re

UNIT_LABELS={'money':'$','money_m':'$m','money_b':'$bn','shares':'shares','shares_m':'m shares',
             'quantity_m':'m units','percent':'%','multiple':'x','count':'count','ratio':'ratio',
             'index':'index','year':'year','days':'days','months':'months','text':'text','date':'date'}
SCALED_UNITS={'money_m':1e6,'money_b':1e9,'shares_m':1e6,'quantity_m':1e6}

def pattern(path):return '.'.join('*' if isinstance(p,int) else p for p in path)

def metadata(item,path):
    specs=item.get('inputMetadata',{});exact='.'.join(map(str,path));wild=pattern(path)
    spec=specs.get(exact,specs.get(wild))
    if spec is None:raise ValueError('Missing authored source metadata: '+item['key']+'/'+exact)
    if spec['unit'] not in UNIT_LABELS:raise ValueError('Unknown declared source unit: '+spec['unit'])
    return spec

def period_for(spec,path,fields):
    period=spec['source']['period']
    if period=='annual-series':
        depth=next(i for i,v in enumerate(path) if isinstance(v,int));parent=fields
        for part in path[:depth]:parent=parent[part]
        count=len(parent);i=path[depth]
        if count>5:raise ValueError('Annual workbook series cannot silently include an overlapping LTM period')
        return 'FY-'+str(count-i-1)
    if period=='quarter-series':
        depth=next(i for i,v in enumerate(path) if isinstance(v,int));parent=fields
        for part in path[:depth]:parent=parent[part]
        count=len(parent)
        if count>8:raise ValueError('Quarterly series exceeds the workbook history')
        return 'Q-'+str(count-path[depth]-1)
    index=next((p+1 for p in path if isinstance(p,int)),1)
    return period.replace('{n}',str(index))

def source_note(spec,path,fields):
    if spec.get('assumption'):
        return spec.get('instruction','Writer-defined limit; the fact-check does not check this assumption.'),None
    source=deepcopy(spec['source']);period=period_for(spec,path,fields);source['period']=period
    if source['kind']=='workbook':
        note=f'{source["sheet"]}!{source["field"]}, {period}.'
        if source.get('calculation'):note+=' Compute '+source['calculation']+'.'
    elif source['kind']=='filing':
        note=f'From the filing: {source["location"]}; {period}. Not confirmed by a workbook row.'
    else:raise ValueError('Unknown source kind')
    unit=spec['unit']
    if unit in SCALED_UNITS:note+=' Bare numbers mean whole units and are converted to '+UNIT_LABELS[unit]+'; include a magnitude suffix when copying a filing table in millions.'
    elif unit=='percent':note+=' Write percentage points, for example 12.5%.'
    if spec.get('modelScale',1)!=1:note+=' The renderer converts this declared unit to the model basis.'
    if spec.get('sign')=='outflow-magnitude':note+=' A reported cash outflow is drawn as a positive spending amount.'
    if path==('period',):note+=' Reporting label only; units are generated by the renderer.'
    return note,source

def numeric_units(item):
    return {spec['unit'] for spec in item.get('inputMetadata',{}).values() if not spec.get('fixed') and spec['unit'] not in ('text','date','year')}

def unit_summary(item):
    units=numeric_units(item)
    preferred=[u for u in ('money_m','money_b','shares_m','quantity_m','money') if u in units]
    if not preferred:preferred=[u for u in ('percent','multiple','index') if u in units]
    return ' / '.join(UNIT_LABELS[u] for u in preferred)

def reporting_label(value):
    if re.search(r'[$€£%]|\b(?:millions?|billions?|shares|units|usd|eur|gbp|bn|mm|m)\b',value,re.I):
        raise ValueError('Reporting-period input must not override the generated unit label')
    return value

def apply_labels(item,fields,scene):
    """Units are calculated labels, never independent writer defaults."""
    summary=unit_summary(item)
    for slot in scene.slots:
        name=slot['name']
        if name=='period' and 'period' in fields:
            label=reporting_label(str(fields['period']))
            slot['example']=label+(' / '+summary if summary else '')
            slot['unitLabel']=True
        elif name in item.get('unitLabels',{}):
            slot['example']=item['unitLabels'][name].format_map(UNIT_LABELS)
            slot['unitLabel']=True
    if summary and not any(s['name']=='period' for s in scene.slots):
        chapter=next((s for s in scene.slots if s['name']=='label-chapter'),None)
        if chapter:
            chapter['box'][2]-=280 if scene.portrait else 420
            x=scene.w-96-(260 if scene.portrait else 400)
            scene.label('unit',summary,x,430 if scene.portrait else 344,260 if scene.portrait else 400,55 if scene.portrait else 42,
                        size=34 if scene.portrait else 28,align='right',colour='quiet')
            scene.slots[-1]['unitLabel']=True
